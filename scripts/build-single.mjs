#!/usr/bin/env node
// Builds outofthebox.md, the single file you can paste into any chat or agent:
// the core skill plus the atlas and heuristics, with links made local.
//
//   node scripts/build-single.mjs          write outofthebox.md
//   node scripts/build-single.mjs --check  exit 1 when outofthebox.md is stale
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const body = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, '').trim()
const demote = (text) => text.replace(/^(#{1,5}) /gm, '#$1 ')

export function buildSingle() {
  const version = read('VERSION').trim()
  const core = body(read('skills/outofthebox/SKILL.md'))
    .replace(/\]\(references\/edge-case-atlas\.md\)/g, '](#edge-case-atlas)')
    .replace(/\]\(references\/heuristics\.md\)/g, '](#heuristics-for-finding-the-next-case)')
  return [
    `<!-- outofthebox ${version}. Generated by scripts/build-single.mjs from skills/; edit those, not this file. -->`,
    '',
    core,
    '',
    '---',
    '',
    demote(read('skills/outofthebox/references/edge-case-atlas.md').trim()),
    '',
    '---',
    '',
    demote(read('skills/outofthebox/references/heuristics.md').trim()),
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = path.join(root, 'outofthebox.md')
  const next = buildSingle()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
    if (current !== next) {
      console.error('outofthebox.md is stale; run node scripts/build-single.mjs')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(out, next)
    console.log(`wrote outofthebox.md (${next.length} characters)`)
  }
}
